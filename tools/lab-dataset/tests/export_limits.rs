/// The throwaway server with the product's schema and the reader.
async fn start() -> Option<(Arc<ClickHouse>, Account)> {
    let server = ClickHouse::start_throwaway().await?;
    for migration in migrate::registry::PRODUCT.clickhouse {
        let statements = migrate::clickhouse::split_statements(migration.sql)
            .unwrap_or_else(|error| panic!("{}: {error}", migration.name));
        for statement in statements {
            server
                .admin(&statement)
                .await
                .unwrap_or_else(|error| panic!("{}: {statement}\n{}", migration.name, error.body));
        }
    }
    let reader = Account {
        user: READER.to_owned(),
        password: Uuid::new_v4().simple().to_string(),
    };
    server
        .query_with(
            &server.admin,
            CREATE_READER,
            &[("param_password", reader.password.as_str())],
        )
        .await
        .unwrap_or_else(|error| panic!("{CREATE_READER}\n{}", error.body));
    for statement in READER_STATEMENTS {
        server.admin_ok(statement).await;
    }
    Some((Arc::new(server), reader))
}

/// A whole hour a few hours ago (inside the table's retention).
fn start_of_data() -> DateTime<Utc> {
    static START: std::sync::OnceLock<DateTime<Utc>> = std::sync::OnceLock::new();
    *START.get_or_init(compute_start)
}

fn compute_start() -> DateTime<Utc> {
    let hour = TimeDelta::hours(1).num_milliseconds();
    let ms = (Utc::now() - TimeDelta::days(2)).timestamp_millis();
    DateTime::from_timestamp_millis(ms - ms.rem_euclid(hour)).unwrap()
}

/// Writes batches `first` to `first + count` of the dense data (`readings` per data point each).
async fn generate_dense(server: &ClickHouse, start_ms: i64, first: u64, count: u64, readings: u64) {
    let (tenant, binding) = (TENANT.to_string(), BINDING.to_string());
    let (device_1, device_2) = (SENSOR_1.to_string(), SENSOR_2.to_string());
    let (start_ms, first, count) = (start_ms.to_string(), first.to_string(), count.to_string());
    let (readings, rows) = (readings.to_string(), (readings * 10).to_string());
    let parameters = [
        ("param_tenant", tenant.as_str()),
        ("param_binding", binding.as_str()),
        ("param_gateway", GATEWAY),
        ("param_stream", STREAM),
        ("param_device_1", device_1.as_str()),
        ("param_device_2", device_2.as_str()),
        ("param_start_ms", start_ms.as_str()),
        ("param_first", first.as_str()),
        ("param_count", count.as_str()),
        ("param_readings", readings.as_str()),
        ("param_rows", rows.as_str()),
    ];
    for statement in [GENERATE_DENSE, GENERATE_COMMITS] {
        server
            .query_with(&server.admin, statement, &parameters)
            .await
            .unwrap_or_else(|error| panic!("{statement}\n{}", error.body));
    }
}

/// A statement of the administrator that the proxy runs before it forwards a read.
#[derive(Clone, Debug)]
struct Change {
    /// The statement of the export, and its number counted from 1, before which this one runs.
    before: (Step, usize),
    statement: &'static str,
    parameters: Vec<(&'static str, String)>,
}

/// The two statements of the export that the changes are placed before.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Step {
    /// The plan of the windows (after the census of devices and points).
    Plan,
    /// The read of a window's rows.
    Rows,
}

/// What the proxy saw.
#[derive(Debug, Default)]
struct Seen {
    /// The answer of each read of rows, in order: bytes from the server, headers included.
    answers: Vec<u64>,
    /// The reads of rows and the plans that arrived so far.
    reads: usize,
    plans: usize,
    /// Each change that ran, in order: the statement it was placed before, and the start of the
    /// receive times (`from_ms`) that statement asked for.
    ran: Vec<((Step, usize), Option<i64>)>,
}

/// A forwarding proxy in front of the throwaway server: one connection per request (it asks the
/// server to close), the request read whole, the changes run before the read they name, the
/// answer read whole, measured, and only then copied back.
///
/// The export sends its statements one at a time, each after the answer of the one before, so
/// a statement's number is the order in which it arrives, given when it arrives. Counting the
/// answers recorded so far instead loses that order: the client can have a whole answer, and send
/// its next statement, before the task that copied the answer has recorded it, so on a loaded
/// machine the third read was numbered 2 and a change meant for it ran before the fourth, into a
/// window already read (Laysi/trustiot-v2#916). Recording the answer before the client gets it
/// also means every answer is recorded when the export returns.
struct Proxy {
    url: String,
    seen: Arc<Mutex<Seen>>,
}

impl Proxy {
    async fn start(server: &Arc<ClickHouse>, changes: Vec<Change>) -> Self {
        let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
        let url = format!("http://{}", listener.local_addr().unwrap());
        let upstream = server.url.trim_start_matches("http://").to_owned();
        let seen = Arc::new(Mutex::new(Seen::default()));
        let (shared, server) = (Arc::clone(&seen), Arc::clone(server));
        tokio::spawn(async move {
            loop {
                let (client, _) = listener.accept().await.unwrap();
                let (upstream, shared, server, changes) = (
                    upstream.clone(),
                    Arc::clone(&shared),
                    Arc::clone(&server),
                    changes.clone(),
                );
                tokio::spawn(async move {
                    forward(client, &upstream, &shared, &server, &changes).await;
                });
            }
        });
        Self { url, seen }
    }

    fn answers(&self) -> Vec<u64> {
        self.seen.lock().unwrap().answers.clone()
    }

    /// Asserts that each of `changes` ran once, before the statement it names, and that a change
    /// placed before the Nth read of rows ran before the read of the Nth window. The tests that
    /// place changes read a window per batch, so the Nth window starts at the Nth batch's receive
    /// time, `start` plus N - 1 minutes.
    fn assert_ran(&self, changes: &[Change], start: DateTime<Utc>) {
        let ran = self.seen.lock().unwrap().ran.clone();
        let expected: Vec<_> = changes
            .iter()
            .map(|change| {
                let window = match change.before {
                    (Step::Rows, number) => Some(
                        (start + TimeDelta::minutes(i64::try_from(number).unwrap() - 1))
                            .timestamp_millis(),
                    ),
                    (Step::Plan, _) => Some(start.timestamp_millis()),
                };
                (change.before, window)
            })
            .collect();
        assert_eq!(
            ran, expected,
            "the changes did not run before the statements they name (statement, its from_ms)"
        );
    }
}

/// The `from_ms` query parameter of the request in `text`: where the statement's receive times
/// start.
fn from_ms(text: &str) -> Option<i64> {
    let line = text.lines().next()?;
    let value = line
        .split(['?', '&', ' '])
        .find_map(|part| part.strip_prefix("param_from_ms="))?;
    value.parse().ok()
}

/// The request in `buffer`, when it is complete: its length.
fn request_length(buffer: &[u8]) -> Option<usize> {
    let head_end = buffer.windows(4).position(|window| window == b"\r\n\r\n")? + 4;
    let head = String::from_utf8_lossy(&buffer[..head_end]).to_ascii_lowercase();
    let body: usize = head
        .lines()
        .find_map(|line| line.strip_prefix("content-length:"))
        .map_or(0, |value| value.trim().parse().unwrap());
    (buffer.len() >= head_end + body).then_some(head_end + body)
}

async fn forward(
    mut client: TcpStream,
    upstream: &str,
    seen: &Mutex<Seen>,
    server: &ClickHouse,
    changes: &[Change],
) {
    let mut request = Vec::new();
    let mut chunk = vec![0; 64 * 1024];
    while request_length(&request).is_none() {
        let read = client.read(&mut chunk).await.unwrap();
        if read == 0 {
            return;
        }
        request.extend_from_slice(&chunk[..read]);
    }
    let text = String::from_utf8_lossy(&request).into_owned();
    let reads_rows = text.contains(ROWS_STATEMENT);
    let step = if reads_rows {
        Some(Step::Rows)
    } else if text.contains(PLAN_STATEMENT) {
        Some(Step::Plan)
    } else {
        None
    };
    if let Some(step) = step {
        // Numbered on arrival (see `Proxy`).
        let number = {
            let mut seen = seen.lock().unwrap();
            let count = match step {
                Step::Rows => &mut seen.reads,
                Step::Plan => &mut seen.plans,
            };
            *count += 1;
            *count
        };
        for change in changes
            .iter()
            .filter(|change| change.before == (step, number))
        {
            let parameters: Vec<(&str, &str)> = change
                .parameters
                .iter()
                .map(|(name, value)| (*name, value.as_str()))
                .collect();
            server
                .query_with(&server.admin, change.statement, &parameters)
                .await
                .unwrap_or_else(|error| panic!("{}\n{}", change.statement, error.body));
            seen.lock()
                .unwrap()
                .ran
                .push(((step, number), from_ms(&text)));
        }
    }
    // Ask the server to close the connection after the answer, so the answer ends at EOF.
    let line_end = request
        .windows(2)
        .position(|window| window == b"\r\n")
        .unwrap()
        + 2;
    request.splice(line_end..line_end, b"Connection: close\r\n".iter().copied());
    let mut server_side = TcpStream::connect(upstream).await.unwrap();
    server_side.write_all(&request).await.unwrap();
    // The whole answer, up to the server's close, recorded before the client gets a byte of it
    // (see `Proxy`).
    let mut answer = Vec::new();
    server_side.read_to_end(&mut answer).await.unwrap();
    if reads_rows {
        seen.lock()
            .unwrap()
            .answers
            .push(u64::try_from(answer.len()).unwrap());
    }
    // The client may give up on an answer over its limit and close first.
    let _ = client.write_all(&answer).await;
    let _ = client.shutdown().await;
}

fn reader_client(url: &str, account: &Account) -> lab_dataset::ClickHouse {
    lab_dataset::ClickHouse::new(url, &account.user, &account.password, None).unwrap()
}

/// Exports `[from, to)` of the data with `limits`.
async fn export(
    clickhouse: &lab_dataset::ClickHouse,
    limits: ReadLimits,
    range: (DateTime<Utc>, DateTime<Utc>),
    out: &Path,
) -> Result<Exported, lab_dataset::Error> {
    let exporter = Exporter::new(&Config::parse(&config_text()).unwrap())
        .unwrap()
        .with_limits(limits);
    tokio::time::timeout(
        EXPORT_TIMEOUT,
        exporter.run(clickhouse, TENANT, GATEWAY, range.0, range.1, out),
    )
    .await
    .expect("the export finished within the generous bound")
}

/// The files of the dataset an export wrote, by path.
fn dataset_files(out: &Path) -> BTreeMap<String, Vec<u8>> {
    let dir = out.join("limits");
    let mut files = BTreeMap::new();
    files.insert(
        "index.toml".to_owned(),
        fs::read(dir.join("index.toml")).unwrap(),
    );
    for entry in fs::read_dir(dir.join("segments")).unwrap() {
        let entry = entry.unwrap();
        files.insert(
            format!("segments/{}", entry.file_name().to_string_lossy()),
            fs::read(entry.path()).unwrap(),
        );
    }
    files
}

/// Asserts that an export left nothing in `out`: neither the dataset nor its partial directory.
fn assert_no_files(out: &Path) {
    let left: Vec<_> = fs::read_dir(out)
        .map(|entries| {
            entries
                .map(|entry| entry.unwrap().file_name().to_string_lossy().into_owned())
                .collect()
        })
        .unwrap_or_default();
    assert!(
        left.is_empty(),
        "the failed export left {left:?} in {out:?}"
    );
}

#[tokio::test(flavor = "multi_thread", worker_threads = 2)]
async fn an_hour_over_the_answer_limit_is_read_in_windows() {
    let Some((server, reader)) = start().await else {
        return;
    };
    let scratch = Scratch::new();
    let start = start_of_data();
    generate_dense(
        &server,
        start.timestamp_millis(),
        0,
        DENSE_BATCHES,
        READINGS_PER_POINT,
    )
    .await;
    let hour = (start, start + TimeDelta::hours(1));
    let proxy = Proxy::start(&server, Vec::new()).await;
    let client = reader_client(&proxy.url, &reader);

    let out = scratch.0.join("default");
    let exported = export(&client, ReadLimits::default(), hour, &out)
        .await
        .unwrap();
    assert_eq!(exported.rows, DENSE_ROWS);
    assert_eq!(exported.batches, DENSE_BATCHES);
    assert_eq!(exported.uncommitted_batches, 0);
    assert_eq!(exported.repeated_rows_dropped, 0);
    let answers = proxy.answers();
    let total: u64 = answers.iter().sum();
    let largest = *answers.iter().max().unwrap();
    println!(
        "dense hour: {} rows, {} windows, answers {answers:?}, total {total} bytes, largest \
         {largest} bytes of the {ANSWER_LIMIT_BYTES}-byte limit",
        exported.rows, exported.windows
    );
    assert_eq!(answers.len() as u64, exported.windows);
    assert!(
        total > ANSWER_LIMIT_BYTES,
        "the hour's answers ({total} bytes) do not pass the limit: it proves nothing"
    );
    assert!(
        exported.windows > 1,
        "one window for an hour over the limit"
    );
    assert!(
        largest < ANSWER_LIMIT_BYTES,
        "an answer of {largest} bytes reaches the limit"
    );

    // The same hour with a window per receive time: the same files, byte for byte.
    let fine = scratch.0.join("fine");
    let fine_exported = export(&client, ONE_RECEIVE_TIME, hour, &fine)
        .await
        .unwrap();
    assert_eq!(fine_exported.windows, DENSE_BATCHES);
    assert!(
        dataset_files(&out) == dataset_files(&fine),
        "windows of one receive time wrote other files than the default windows"
    );

    // A quarter hour that fits in one answer: one window, and the files of the export in
    // windows of one receive time, which is the reading in many windows against the reading
    // in one.
    let half = (start, start + TimeDelta::minutes(15));
    let (whole, split) = (scratch.0.join("whole"), scratch.0.join("split"));
    let whole_exported = export(&client, ReadLimits::default(), half, &whole)
        .await
        .unwrap();
    assert_eq!(whole_exported.windows, 1, "the quarter hour is one window");
    assert_eq!(whole_exported.rows, DENSE_ROWS / 4);
    let split_exported = export(&client, ONE_RECEIVE_TIME, half, &split)
        .await
        .unwrap();
    assert_eq!(split_exported.windows, DENSE_BATCHES / 4);
    assert!(
        dataset_files(&whole) == dataset_files(&split),
        "the quarter hour read in one window differs from the same read in many"
    );
    println!(
        "quarter hour: {} windows against {}, {} files identical",
        whole_exported.windows,
        split_exported.windows,
        dataset_files(&whole).len()
    );

    // The result of the first export passes the checker.
    lab_dataset::Dataset::open(out.join("limits").join("index.toml")).unwrap();
}

