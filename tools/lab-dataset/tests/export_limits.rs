//! The limits of `lab-dataset export` on data that is large where it matters (Laysi/trustiot-v2#836,
//! the advanced verification deferred from Laysi/trustiot-v2#837), in a throwaway ClickHouse with
//! the product's schema:
//!
//! - an hour of rows whose answer is longer than the HTTP client's 16 MiB limit (`migrate::http`)
//!   exports successfully in several windows; each window's answer is under the limit and the
//!   files are those of an export with other windows, byte for byte; a quarter hour that fits in one
//!   answer is read in one window and its files equal those of the export in windows of one
//!   receive time each;
//! - the rows of one millisecond that alone pass 16 MiB cannot be split: the export fails with a
//!   message that names the cause and leaves no files;
//! - rows written or deleted while the export runs are refused (`the rows in the range changed
//!   ...`) and leave no files. The change happens at a chosen read, deterministically: the
//!   export talks to ClickHouse through a forwarding proxy in this test that, before it
//!   forwards the Nth read of rows, runs a statement of the administrator.
//!
//! The export's own reads are SELECTs of the account under test (`datasets/lab/README.md`,
//! 「匯出」); the generated data and the changes are written by the administrator. The data is
//! generated at run time and never committed. Always a throwaway container.

